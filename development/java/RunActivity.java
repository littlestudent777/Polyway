    private void setStage(int stageIndex) {
        ExcursionStage stage = stages.get(stageIndex);

        // Установка заголовка и описания
        titleTextView.setText(stage.title);
        descriptionTextView.setText(stage.description);

        // Построение маршрута
        buildRoute(stage.startPoint, stage.endPoint);
    }

    private void buildRoute(Point start, Point end) {
        // Очистка предыдущего маршрута
        if (line != null) {
            mapObjects.remove(line);
            line = null;
        }
        mapObjects.clear();

        // Добавление маркеров
        addMarker(start, "Начало", Color.BLUE);
        addMarker(end, "Конец", Color.GREEN);

        // Создание точек маршрута
        List<RequestPoint> points = new ArrayList<>();
        points.add(new RequestPoint(start, RequestPointType.WAYPOINT, null));
        points.add(new RequestPoint(end, RequestPointType.WAYPOINT, null));

        // Настройка параметров маршрута
        DrivingOptions options = new DrivingOptions();
        options.setRoutesCount(1);

        VehicleOptions vehicleOptions = new VehicleOptions();

        // Запрос маршрута
        drivingSession = drivingRouter.requestRoutes(points, options, vehicleOptions, this);

        // Перемещение камеры для отображения маршрута
        mapView.getMap().move(
                new CameraPosition(start, 17.0f, 0.0f, 0.0f),
                new Animation(Animation.Type.SMOOTH, 0),
                null);
    }

    private void addMarker(Point point, String text, int color) {
        PlacemarkMapObject marker = mapObjects.addPlacemark(point);
        marker.setIcon(ImageProvider.fromResource(this, R.drawable.ic_map_marker));
        marker.setText(text);
    }

    @Override
    public void onDrivingRoutes(List<DrivingRoute> routes) {
        if (routes.isEmpty()) {
            Log.e(TAG, "No routes found");
            return;
        }

        // Отображение маршрута
        DrivingRoute route = routes.get(0);
        Polyline polyline = route.getGeometry();

        if (line != null) {
            mapObjects.remove(line);
        }
        line = mapObjects.addPolyline(polyline);
        line.setStrokeColor(Color.RED);
        line.setStrokeWidth(5f);
    }

    @Override
    public void onDrivingRoutesError(Error error) {
        Log.e(TAG, "Error building route: " + error.toString());
    }

    @Override
    protected void onStart() {
        super.onStart();
        mapView.onStart();
        MapKitFactory.getInstance().onStart();
    }

    @Override
    protected void onStop() {
        mapView.onStop();
        MapKitFactory.getInstance().onStop();
        super.onStop();
    }

    @Override
    protected void onDestroy() {
        super.onDestroy();
        if (drivingSession != null) {
            drivingSession.cancel();
        }
    }
